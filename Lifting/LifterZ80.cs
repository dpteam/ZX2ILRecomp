using ZX2ILRecomp.Common;
using ZX2ILRecomp.Core;

namespace ZX2ILRecomp.Lifting;

/// <summary>
/// Everything an emitter needs to know about the snapshot being lifted.
/// Passed by reference so emitters never reach back into the pipeline.
/// </summary>
public sealed class LifterContext
{
    public LifterContext(ZxSnapshot snapshot, AnalysisResultZ80 model, string gameName)
    {
        Snapshot = snapshot;
        Model = model;
        DisplayName = string.IsNullOrWhiteSpace(gameName) ? "Game" : gameName;
        GameName = FileSystemUtil.SanitizeIdentifier(gameName);

        List<ushort> labels = new(model.Labels);
        labels.Sort();
        Labels = labels;

        Entry = model.Entry != 0 ? model.Entry : (ushort)0x8000;
        HasEntry = model.Instructions.ContainsKey(Entry);
    }

    public ZxSnapshot Snapshot { get; }

    public AnalysisResultZ80 Model { get; }

    /// <summary>Sanitised identifier used for the namespace.</summary>
    public string GameName { get; }

    /// <summary>Raw snapshot name, shown in the window title.</summary>
    public string DisplayName { get; }

    /// <summary>
    /// Seconds the generated game waits before screenshotting itself into an
    /// icon. Baked into the build so a lifted game captures without arguments;
    /// 0 disables it.
    /// </summary>
    public int CaptureIconSeconds { get; init; } = 5;

    /// <summary>Every emitted label, ascending.</summary>
    public IReadOnlyList<ushort> Labels { get; }

    public ushort Entry { get; }

    public bool HasEntry { get; }
}

/// <summary>
/// Turns the analysis into one self-contained C# source file.
///
/// The emitted program is not an interpreter wrapper: every reachable address
/// becomes its own static method <c>Lxxxx</c> that returns the next address.
/// A three-level dispatch (<c>pc&gt;&gt;8</c> → page → address) keeps that cheap,
/// and only addresses the analysis could not prove fall back to the runtime
/// interpreter.
/// </summary>
public sealed class LifterZ80
{
    private readonly LifterContext _ctx;

    public LifterZ80(ZxSnapshot snapshot, AnalysisResultZ80 model, string gameName, int captureIconSeconds = 5)
    {
        _ctx = new LifterContext(snapshot, model, gameName)
        {
            CaptureIconSeconds = Math.Max(0, captureIconSeconds)
        };
    }

    public string Generate()
    {
        System.Text.StringBuilder sb = new(1 << 20);
        EmitWriter w = new(sb);

        w.Line("// <auto-generated>");
        w.Line("// Generated by ZX2ILRecomp " + BuildInfo.Version + " from \"" + EmitWriter.Escape(_ctx.DisplayName) + "\".");
        w.Line("// Static Z80 recompilation: each label below is one original instruction.");
        w.Line("// Do not edit; re-lift the snapshot instead.");
        w.Line("// </auto-generated>");
        w.Blank();
        w.Line("using System;");
        w.Line("using System.Collections.Generic;");
        w.Line("using System.Drawing;");
        w.Line("using System.Drawing.Drawing2D;");
        w.Line("using System.Drawing.Imaging;");
        w.Line("using System.IO;");
        w.Line("using System.Runtime.InteropServices;");
        w.Line("using System.Threading;");
        w.Line("using System.Windows.Forms;");
        w.Blank();
        w.Open("namespace Lifted." + _ctx.GameName);

        ProgramEmitter.Emit(w, _ctx);
        RuntimeEmitter.Emit(w, _ctx);
        MemoryEmitter.Emit(w, _ctx);
        UlaEmitter.Emit(w, _ctx);
        AyEmitter.Emit(w, _ctx);
        AudioEmitter.Emit(w, _ctx);
        FormEmitter.Emit(w, _ctx);

        w.Close();
        return sb.ToString();
    }
}

/// <summary>Version string baked into generated code and reports.</summary>
public static class BuildInfo
{
    public const string Version = "0.11.0";
}
